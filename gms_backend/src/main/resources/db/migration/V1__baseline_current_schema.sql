-- V1__baseline_current_schema.sql
--
-- The schema the running application expects, captured once from a disposable database and
-- reviewed line by line. ADR-022 sanctions exactly this route -- "a one-off export of a
-- disposable update-generated database, reviewed line by line before it becomes V1" -- and
-- the objection it records against generate-then-hand-edit (no composite foreign keys, no
-- CHECKs, no partial uniques, no indexes) is answered by V3-V5, not by pretending the export
-- contains them.
--
-- Provenance, so this file is reproducible rather than merely plausible:
--   branch        feat/stage2-flyway-baseline at a8748f7
--   runtime       PostgreSQL 16.15 (image postgres:16-alpine), the compose container
--   capture       boot with JPA_DDL_AUTO=update + FLYWAY_ENABLED=false against an empty
--                 scratch database, then pg_dump --schema-only --no-owner --no-privileges
--   measured      38 tables, 14 UNIQUE constraints, 123 FOREIGN KEYs, 0 `idx_*` secondary
--                 indexes (the 14 unique constraints each back an index; none of them is
--                 tenant-leading). Re-counted against this file applied to an empty server:
--                 pg_constraint contype='f' -> 123. An earlier draft of this line said 128,
--                 which was a carry-forward from a document rather than a query.
--   names         the uk*/fk* tokens are Hibernate-generated and deliberately preserved:
--                 renaming them here would make V3's drops unverifiable against a real server
--
-- What this baseline is NOT: it is not the design. No table here has a tenant-scoped index,
-- four numbered natural keys are globally unique where they should be unique per school
-- (DB-07), timetables.classroom_id forbids a second academic year, the role collection table
-- has no key at all, and ten tables do not carry the tenant. Those are what V2-V5 change.
-- Anything after this marker is what Hibernate wrote.

